export function getLegacyBoardMapping(legacyBoard) {
  const mapping = LEGACY_BOARD_MAP[legacyBoard];

  if (!mapping) {
    throw new Error(`Unknown legacy board: ${legacyBoard}`);
  }

  return mapping;
}

export function mapLegacyMemberLevel(level) {
  const normalized = Number(level);

  if (!Number.isFinite(normalized) || normalized < 6) {
    return 2;
  }

  if (normalized >= 10) {
    return 10;
  }

  return 6;
}

export function toRedirectRecord({ boTable, wrId, newBoard, newWrId }) {
  return {
    legacyPath: `/renewal/bbs/board.php?bo_table=${boTable}&wr_id=${wrId}`,
    targetPath: `/bbs/board.php?bo_table=${newBoard}&wr_id=${newWrId}`,
    legacyBoard: boTable,
    legacyPostId: Number(wrId),
    targetBoard: newBoard,
    targetPostId: Number(newWrId),
  };
}
